def _all_entries() -> list[RuleEntry | rule_table.AllowedAlternative]:
    return [
        *rule_table.RULES_BY_ID.values(),
        *(alt for alts in rule_table.ALLOWED_ALTERNATIVES.values() for alt in alts),
    ]


def _unreviewed_rule_ids() -> list[str]:
    return [
        rule_id
        for rule_id, rule in rule_table.RULES_BY_ID.items()
        if not rule_table.is_reviewed(rule)
    ]


def _unreviewed_alternatives() -> list[str]:
    return [
        f"{proposed} / {conflict} → {alt.drug_id}"
        for (proposed, conflict), alternatives in rule_table.ALLOWED_ALTERNATIVES.items()
        for alt in alternatives
        if not rule_table.is_reviewed(alt)
    ]


def _pending_text() -> str:
    rules, alternatives = _unreviewed_rule_ids(), _unreviewed_alternatives()
    parts = []
    if rules:
        parts.append("rules " + ", ".join(rules))
    if alternatives:
        parts.append(f"{len(alternatives)} alternatives")
    return " and ".join(parts)


def _status_line() -> str:
    entries = _all_entries()
    reviewed = [entry for entry in entries if rule_table.is_reviewed(entry)]
    if len(reviewed) == len(entries):
        return (
            f"**Status: REVIEWED** by {rule_table.SPECIALIST_REVIEWER} on "
            f"{rule_table.SPECIALIST_REVIEW_DATE}. Every rule and alternative below was confirmed "
            "as it stands. The project is a concept demonstrator, not a medical device. Every "
            "patient is synthetic."
        )
    if reviewed:
        pending = _pending_text()
        return (
            f"**Status: NOT FULLY REVIEWED.** {rule_table.SPECIALIST_REVIEWER} confirmed "
            f"{len(reviewed)} of {len(entries)} rules and alternatives on "
            f"{rule_table.SPECIALIST_REVIEW_DATE}. Entries marked *not reviewed* were added or "
            f"changed later and have not been checked by a clinical specialist ({pending}). The "
            "project is a concept demonstrator, not a medical device. Every patient is synthetic."
        )
    return (
        "**Status: NOT FULLY REVIEWED.** Entries marked *not reviewed* have not been checked by a "
        "clinical specialist. The project is a concept demonstrator, not a medical device. Every "
        "patient is synthetic."
    )


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _review_mark(entry: RuleEntry | rule_table.AllowedAlternative) -> str:
    if rule_table.is_reviewed(entry):
        return f"{entry.reviewed_by}, {entry.reviewed_on}"
    return "not reviewed"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines.extend("| " + " | ".join(_cell(c) for c in row) + " |" for row in rows)
    return "\n".join(lines)


def _drug_section() -> str:
    rows = [[d.drug_id, d.name, d.drug_class] for d in rule_table.DRUGS]
    return "## Drug list and classes\n\n" + _table(["Drug ID", "Name", "Class"], rows)


def _rule_section() -> str:
    rows: list[list[str]] = []
    allergy = rule_table.ALLERGY_RULE
    rows.append(
        [
            allergy.rule_id,
            "Any drug",
            "Drug ID, active ingredient or class equals a recorded allergy (exact match)",
            f"{allergy.status} / {allergy.risk_level}",
            allergy.conflict_type,
            allergy.reason,
            allergy.source,
            _review_mark(allergy),
        ]
    )
    for rule in rule_table.CONTEXT_RULES:
        parts = []
        if rule.diagnosis:
            parts.append(f"Coded diagnosis {rule.diagnosis} (coded or a quoted note finding)")
        if rule.chronic_class:
            parts.append(f"a chronic medication of class {rule.chronic_class}")
        if rule.history:
            parts.append(f"Past medical history {rule.history} (recorded or a quoted note finding)")
        condition = ", and ".join(parts)
        rows.append(
            [
                rule.rule_id,
                f"Class {rule.applies_to_class}",
                condition,
                f"{rule.status} / {rule.risk_level}",
                rule.conflict_type,
                rule.reason,
                rule.source,
                _review_mark(rule),
            ]
        )
    for renal in rule_table.RENAL_RULES:
        rows.append(
            [
                renal.rule_id,
                renal.drug_id,
                f"{renal.basis} < {renal.threshold:g}",
                f"{renal.status} / {renal.risk_level}",
                renal.conflict_type,
                renal.reason,
                renal.source,
                _review_mark(renal),
            ]
        )
    for unknown in rule_table.RENAL_UNKNOWN_RULES.values():
        rows.append(
            [
                unknown.rule_id,
                "Drugs with a renal rule using this lab",
                f"Lab for {unknown.basis} is missing",
                f"{unknown.status} / {unknown.risk_level}",
                unknown.conflict_type,
                unknown.reason,
                unknown.source,
                _review_mark(unknown),
            ]
        )
    for lab in rule_table.LAB_RULES:
        sign = ">" if lab.comparison is rule_table.LabComparison.ABOVE else "<"
        rows.append(
            [
                lab.rule_id,
                "Classes " + ", ".join(lab.applies_to_classes),
                f"{_LAB_NAMES.get(lab.lab, lab.lab)} {sign} {lab.threshold:,.1f} "
                "(strictest rule on this lab shown)",
                f"{lab.status} / {lab.risk_level}",
                lab.conflict_type,
                lab.reason,
                lab.source,
                _review_mark(lab),
            ]
        )
    for missing in rule_table.LAB_UNKNOWN_RULES:
        rows.append(
            [
                missing.rule_id,
                "Classes " + ", ".join(missing.applies_to_classes),
                f"{_LAB_NAMES.get(missing.lab, missing.lab)} is missing",
                f"{missing.status} / {missing.risk_level}",
                missing.conflict_type,
                missing.reason,
                missing.source,
                _review_mark(missing),
            ]
        )
    headers = ["Rule ID", "Applies to", "Condition", "Status / tier", "Conflict", "Card reason"]
    return "## Rules\n\n" + _table([*headers, "Source", "Review"], rows)


def _guidance_section() -> str:
    if not any(rule.dose_guidance is not None for rule in rule_table.RENAL_RULES):
        return (
            "## Numeric renal dose guidance\n\n"
            "None. Q-5 (specialist review): every renal card shows "
            f'"{rule_table.RENAL_FALLBACK_GUIDANCE}" and no numeric dose.'
        )
    rows = [
        [
            rule.rule_id,
            rule.dose_guidance or "(none: card shows the fallback)",
            rule_table.shown_dose_guidance(rule),
            _review_mark(rule),
        ]
        for rule in rule_table.RENAL_RULES
        if rule.dose_guidance is not None
    ]
    return "## Numeric renal dose guidance (hidden until you sign it off)\n\n" + _table(
        ["Rule ID", "Proposed text", "Currently shown on the card", "Review"], rows
    )


def _alternative_section() -> str:
    rows = [
        [
            f"{proposed} / {conflict}",
            alt.drug_id,
            f"{alt.dose_text}, {alt.route}, {alt.frequency}",
            rule_table.shown_alternative_dose(alt),
            alt.source,
            _review_mark(alt),
        ]
        for (proposed, conflict), alternatives in rule_table.ALLOWED_ALTERNATIVES.items()
        for alt in alternatives
    ]
    return "## Allowed alternatives (proposed drug / conflict type)\n\n" + _table(
        [
            "Proposed drug / conflict",
            "Alternative",
            "Proposed dose",
            "Shown now",
            "Source",
            "Review",
        ],
        rows,
    )


_LAB_NAMES = {
    "potassium_mmol_l": "Potassium (mmol/L)",
    "platelets_per_ul": "Platelets (per µL)",
}


def _alternative_text(card: DecisionCard) -> str:
    if card.alternative is None:
        return "none on the rules card"
    return f"{card.alternative.name}, {card.alternative.dose_text}"


def _card_block(card: DecisionCard) -> str:
    rules = "\n".join(f"  - `{r.rule_id}`: {r.reason}" for r in card.fired_rules) or "  - none"
    crcl = "not computed" if card.crcl_ml_min is None else f"{card.crcl_ml_min:g} mL/min"
    return (
        f"- Status / tier: **{card.status}** / {card.risk_level}\n"
        f"- Headline: {card.headline}\n"
        f"- Rationale: {card.rationale}\n"
        f"- Renal adjustment flag: {card.renal_adjustment_required}; Cockcroft-Gault: {crcl}\n"
        f"- Fired rules:\n{rules}\n"
        f"- Source: `{card.source}`; alternative: {_alternative_text(card)}"
    )


def _preset_section(preset: Preset) -> str:
    context, order = preset.request.context, preset.request.order
    labs = context.labs
    card = rules_card(preset.request)
    return (
        f"### Preset {preset.preset_id}: {preset.title}\n\n"
        f"*{preset.synthetic_label}.*\n\n"
        f"- Patient: {context.age} years, sex {context.sex}, {context.weight_kg:g} kg; "
        f"creatinine {labs.creatinine_mg_dl} mg/dL, eGFR {labs.egfr_ml_min_1_73m2}\n"
        f"- Coded diagnoses: {', '.join(context.diagnoses) or 'none'}; past medical history: "
        f"{', '.join(context.history) or 'none'}; chronic medication: "
        f"{', '.join(context.chronic_medications) or 'none'}; allergies: "
        f"{', '.join(context.allergies) or 'none'}\n"
        f"- Note: {context.ed_note}\n"
        f"- Proposed order: {order.drug_id} {order.dose_text} {order.route} {order.frequency}\n\n"
        f"Rules card (Layer 1 only):\n\n{_card_block(card)}\n"
    )


def _final_card_section() -> str:
    expected = PRESET_A_EXPECTED_FINAL_CARD
    return (
        "## Preset A: expected final card text\n\n"
        "On the coded record alone the rules say `NO_ISSUE`: the suspected ACS is only in the "
        "free-text note. The local model reads the note and returns the finding with a quote; "
        "once the quote is found word for word, the rules run again and `NSAID_ANTIPLATELET_ACS` "
        "fires, shown with the clinician's words, for example "
        "`From the clinician's note: “Suspected ACS; ECG and troponin pending.”` "
        "(ADR 0006). The wording below is illustrative, and the alternative must pass the rules "
        "again before it is shown.\n\n"
        f"- Status: **{expected['status']}**\n"
        f"- Headline: {expected['headline']}\n"
        f"- Rationale: {expected['rationale']}\n"
        f"- Alternative: {expected['alternative']}\n"
    )


def _source_check_section() -> str:
    rows = [list(row) for row in SOURCE_CHECK_ROWS]
    return SOURCE_CHECK_INTRO + "\n\n" + _table(["Rule(s)", "Checked against", "Result"], rows)


def _question_section() -> str:
    lines = [f"{i}. {q}" for i, q in enumerate(rule_table.SPECIALIST_QUESTIONS, start=1)]
    return (
        "## Questions for the specialist\n\n"
        "Raised before the review. The specialist confirmed the table as it stands and did not "
        "answer these one by one, so they stay open for the next review.\n\n" + "\n".join(lines)
    )


def _signoff_section() -> str:
    pending = _unreviewed_rule_ids() + _unreviewed_alternatives()
    blank = (
        "Reviewer name and role: ____________________  Date: ____________\n\n"
        "Corrections are applied in the rule table; the reviewer name and date "
        "are then recorded on each confirmed entry."
    )
    earlier = (
        f"Reviewed by: {rule_table.SPECIALIST_REVIEWER}. Date: "
        f"{rule_table.SPECIALIST_REVIEW_DATE}. Outcome: confirmed without corrections; Q-5 "
        'answered ("consult SmPC", no numeric renal dose).'
    )
    if not pending:
        return (
            f"## Sign-off\n\n{earlier}\n\n"
            "Later corrections are applied in the rule table; a new or changed "
            "entry is unreviewed until the specialist signs it off."
        )
    if len(pending) < len(_all_entries()):
        return (
            f"## Sign-off\n\n{earlier} That review covered every entry that carries a review "
            f"date.\n\nAwaiting sign-off: {', '.join(pending)}.\n\n{blank}"
        )
    return f"## Sign-off\n\n{blank}"


def render() -> str:
    """Return the whole review sheet as Markdown."""
    presets = "## Preset cases and their rules cards\n\n" + "\n".join(
        _preset_section(PRESETS[key]) for key in sorted(PRESETS)
    )
    sections = [
        HEADER.format(status=_status_line()),
        _drug_section(),
        _rule_section(),
        _guidance_section(),
        _alternative_section(),
        presets,
        _final_card_section(),
        _source_check_section(),
        _question_section(),
        _signoff_section(),
    ]
    return "\n\n".join(section.rstrip("\n") for section in sections) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    args = parser.parse_args()
    text = render()
    if args.stdout:
        print(text)
    else:
        OUTPUT_PATH.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
